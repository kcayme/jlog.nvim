local detect = require("jlog.parse.detect")
local config = require("jlog.config")
local function head(name)
  return table.concat(vim.fn.readfile("tests/fixtures/" .. name, "b"), "\n"):sub(1, 65536)
end

describe("detect", function()
  local opts = config.setup()
  it("should detect each format", function()
    assert.are.equal("loki", detect.detect(head("loki.json"), opts))
    assert.are.equal("jsonl", detect.detect(head("app.jsonl"), opts))
    assert.are.equal("array", detect.detect(head("array.json"), opts))
  end)
  it("should not claim non-logs", function()
    assert.is_nil(detect.detect(head("package.json"), opts))
    assert.is_nil(detect.detect("", opts))
    assert.is_nil(detect.detect("just some text\nmore text\n", opts))
  end)
  it("should detect jsonl when lines start with a bracketed prefix", function()
    local text = '[INFO] {"msg":"a","level":"INFO"}\n[2026-10-22] {"msg":"b","level":"WARN"}\n'
    assert.are.equal("jsonl", detect.detect(text, opts))
    assert.are.equal("array", detect.detect(' [\n  {"msg":"a"}]', opts))
  end)
end)
