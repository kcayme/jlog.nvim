local json = require("jlog.parse.json")

describe("json.parse", function()
  it("should keep key order, duplicate keys and exact number literals", function()
    local node = json.parse_all('{"ts":"x","b":12345678901234567890,"a":1,"a":2,"f":-1.5e3}')
    assert.are.same({ "ts", "b", "a", "a", "f" }, node.keys)
    assert.are.equal("12345678901234567890", node.vals[2].lit)
    assert.are.equal("-1.5e3", node.vals[5].lit)
  end)

  it("should decode escapes in strings and keep the literal", function()
    local node = json.parse_all('{"m":"he said \\"hi\\"\\n\\u00e9"}')
    assert.are.equal('he said "hi"\né', node.vals[1].str)
    assert.are.equal('"he said \\"hi\\"\\n\\u00e9"', node.vals[1].lit)
  end)

  it("should return offsets and the position after the value", function()
    local node, after = json.parse('  [1, {"a":null}] tail')
    assert.are.equal(3, node.s)
    assert.are.equal(17, node.e)
    assert.are.equal(18, after)
    assert.are.equal("null", node.vals[2].vals[1].t)
  end)

  it("should fail on invalid input", function()
    assert.is_nil(json.parse_all('{"a":1'))
    assert.is_nil(json.parse_all('{"a":1} x'))
    assert.is_nil(json.parse_all("ERROR something broke"))
  end)
end)

describe("json.find and unwrap", function()
  it("should find JSON after a text prefix", function()
    local node, prefix = json.find('API error: 500 - {"code":500,"error":"x"}')
    assert.are.equal("API error: 500 - ", prefix)
    assert.are.same({ "code", "error" }, node.keys)
  end)

  it("should unwrap double and triple encoded strings up to max_depth", function()
    local text = '{"line":"{\\"err\\":\\"API error: 500 - {\\\\\\"code\\\\\\":500}\\"}"}'
    local node = json.unwrap(json.parse_all(text), 4)
    local line = node.vals[1]
    assert.are.equal("", line.prefix)
    local err = line.inner.vals[1]
    assert.are.equal("API error: 500 - ", err.prefix)
    assert.are.equal("500", err.inner.vals[1].lit)
    assert.is_nil(json.unwrap(json.parse_all(text), 1).vals[1].inner.vals[1].inner)
  end)

  it("should leave non-JSON strings alone", function()
    local node = json.unwrap(json.parse_all('{"m":"see {braces}"}'), 4)
    assert.is_nil(node.vals[1].inner)
  end)
end)

describe("json edge cases", function()
  it("should parse empty containers with offsets", function()
    local object = json.parse_all("{}")
    local array = json.parse_all(" [] ")
    assert.are.same({ "object", 1, 2, {}, {} }, { object.t, object.s, object.e, object.keys, object.vals })
    assert.are.same({ "array", 2, 3, {} }, { array.t, array.s, array.e, array.vals })
  end)

  it("should decode unicode escapes including surrogate pairs", function()
    local node = json.parse_all('"\\u00e9\\ud83d\\ude00"')
    assert.are.equal("\195\169\240\159\152\128", node.str)
    assert.are.equal('"\\u00e9\\ud83d\\ude00"', node.lit)
  end)

  it("should return an error message for unterminated strings and trailing commas", function()
    for _, text in ipairs({ '{"a":"x', "[1,]", '{"a":1,}' }) do
      local node, err = json.parse_all(text)
      assert.is_nil(node)
      assert.are.equal("string", type(err))
    end
  end)

  it("should parse from a non-1 start position", function()
    local node, after = json.parse('xx {"a":1} yy', 3)
    assert.are.equal(4, node.s)
    assert.are.equal(10, node.e)
    assert.are.equal(11, after)
  end)

  it("should cap nesting depth at 512", function()
    local node, err = json.parse_all(("["):rep(100000))
    assert.is_nil(node)
    assert.truthy(err:find("nesting too deep at", 1, true))
    assert.truthy(json.parse_all(("["):rep(512) .. ("]"):rep(512)))
    assert.is_nil(json.parse_all(("["):rep(513) .. ("]"):rep(513)))
  end)

  it("should return an empty prefix for whitespace-padded whole JSON", function()
    local node, prefix = json.find('  {"a":1}  ')
    assert.are.equal("", prefix)
    assert.are.equal(3, node.s)
  end)

  it("should try later candidates when an earlier bracket is not JSON", function()
    local node, prefix = json.find('[WARN] {"a":1}')
    assert.are.equal("[WARN] ", prefix)
    assert.are.same({ "a" }, node.keys)
  end)

  it("should give up after 8 candidates", function()
    assert.is_nil(json.find(("{x "):rep(8) .. '{"a":1}'))
    assert.truthy(json.find(("{x "):rep(7) .. '{"a":1}'))
  end)

  it("should end strings correctly around escaped backslashes and quotes", function()
    local node = json.parse_all('{"a\\\\":"x\\\\","b":"q\\\\\\"","c":"\\\\\\\\"}')
    assert.are.same({ "a\\", "b", "c" }, node.keys)
    assert.are.equal("x\\", node.vals[1].str)
    assert.are.equal('q\\"', node.vals[2].str)
    assert.are.equal('"\\\\\\\\"', node.vals[3].lit)
  end)

  it("should close several containers at once and keep number literal forms", function()
    local node = json.parse_all('{"a":[[1.50],[2E+3,-0]],"b":{"c":{}}}')
    assert.are.equal("1.50", node.vals[1].vals[1].vals[1].lit)
    assert.are.equal("2E+3", node.vals[1].vals[2].vals[1].lit)
    assert.are.equal("-0", node.vals[1].vals[2].vals[2].lit)
    assert.are.equal(37, node.e)
    assert.are.same({ "c" }, node.vals[2].keys)
  end)

  it("should report errors inside nested containers", function()
    local node, err = json.parse_all('{"a":[1 2]}')
    assert.is_nil(node)
    assert.are.equal('unexpected character "2" at 9', err)
    assert.is_nil((json.parse_all('{"a":[1,]}')))
    assert.is_nil((json.parse_all('{"a" 1}')))
    assert.is_nil((json.parse_all('{"a":-}')))
  end)

  it("should unwrap nothing when max_depth is 0", function()
    local node = json.unwrap(json.parse_all('{"line":"{\\"a\\":1}"}'), 0)
    assert.is_nil(node.vals[1].inner)
  end)
end)

describe("json.object_at", function()
  it("should return the position and decoded object after a prefix", function()
    local pos, decoded = json.object_at('2026-10-22T10:00:01Z {"level":"INFO"}')
    assert.are.equal(22, pos)
    assert.are.equal("INFO", decoded.level)
  end)

  it("should return nil for plain text, invalid JSON and non-objects", function()
    assert.is_nil(json.object_at("goroutine 1 [running]:"))
    assert.is_nil(json.object_at('x {"a":'))
    assert.is_nil(json.object_at("{}x"))
  end)
end)
